def _env_int(name: str, default: int, minimum: int = 0) -> int:
    try:
        return max(minimum, int(os.environ.get(name, default)))
    except (TypeError, ValueError):
        return default


# ---------------------------------------------------------------------------
# Per-principal daily generation quota
# ---------------------------------------------------------------------------
class DailyQuota:
    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._counts: dict[tuple[str, str], int] = {}

    @staticmethod
    def limit() -> int:
        return _env_int("DAILY_GENERATION_QUOTA", 50)

    def consume(self, principal_id: str, amount: int = 1) -> None:
        day = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        key = (principal_id, day)
        with self._lock:
            # Drop counters from previous days.
            for k in [k for k in self._counts if k[1] != day]:
                del self._counts[k]
            used = self._counts.get(key, 0)
            if used + amount > self.limit():
                raise HTTPException(
                    status_code=429,
                    detail="Daily generation quota exceeded. Try again tomorrow (UTC).",
                )
            self._counts[key] = used + amount

    def reset(self) -> None:
        with self._lock:
            self._counts.clear()


DAILY_QUOTA = DailyQuota()


def consume_quota(principal: Principal = Depends(require_admin)) -> Principal:
    """Dependency: admin + one unit of the caller's daily generation quota."""
    DAILY_QUOTA.consume(principal.user_id)
    return principal


# ---------------------------------------------------------------------------
# Global concurrency caps
# ---------------------------------------------------------------------------
class ConcurrencyLimiter:
    def __init__(self, env_name: str, default: int) -> None:
        self._env_name = env_name
        self._default = default
        self._lock = threading.Lock()
        self._active = 0

    def limit(self) -> int:
        return _env_int(self._env_name, self._default, minimum=1)

    @property
    def active(self) -> int:
        return self._active

    def try_acquire(self) -> bool:
        with self._lock:
            if self._active >= self.limit():
                return False
            self._active += 1
            return True

    def release(self) -> None:
        with self._lock:
            self._active = max(0, self._active - 1)

    def reset(self) -> None:
        with self._lock:
            self._active = 0


PENDING_RENDERS = ConcurrencyLimiter("MAX_PENDING_RENDERS", 3)
VOICE_SESSIONS = ConcurrencyLimiter("MAX_VOICE_SESSIONS", 2)


def acquire_render_slot() -> None:
    if not PENDING_RENDERS.try_acquire():
        raise HTTPException(
            status_code=429,
            detail="Too many renders in progress. Try again when a current render finishes.",
        )


def max_voice_session_seconds() -> int:
    return _env_int("MAX_VOICE_SESSION_SECONDS", 900, minimum=1)


# ---------------------------------------------------------------------------
# CORS / WebSocket Origin
# ---------------------------------------------------------------------------
def allowed_origins() -> list[str]:
    raw = os.environ.get("ALLOWED_ORIGINS") or ""
    return [o.strip().rstrip("/") for o in raw.split(",") if o.strip()]


_LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1"}


def origin_allowed(headers: Mapping[str, str]) -> bool:
    """Validate the WebSocket ``Origin`` header.

    - Same-origin is always allowed: Origin host[:port] must equal the Host header.
    - ``ALLOWED_ORIGINS`` adds extra exact-match origins (e.g. a Teams host).
    - ``AUTH_MODE=disabled`` additionally accepts localhost origins (Vite
      dev proxy) and a missing Origin (non-browser local tooling).
    """
    origin = (headers.get("origin") or "").strip().rstrip("/")
    dev = auth_mode() == "disabled"
    if not origin:
        return dev
    if origin in allowed_origins():
        return True
    try:
        parts = urlsplit(origin)
    except ValueError:
        return False
    host = (headers.get("host") or "").strip().lower()
    if parts.scheme in {"http", "https"} and parts.netloc.lower() == host and host:
        return True
    if dev:
        try:
            hostname = (urlsplit(origin).hostname or "").lower()
        except ValueError:
            return False
        return hostname in _LOCAL_HOSTS
    return False
